// Preserve Original Content
// =====================================

// Save the original English text of each text node.
const originalTextNodes = new WeakMap();

// Save the original English attributes of each element.
const originalAttributes = new WeakMap();


// =====================================
// Normalize Text
// =====================================

function normalize(value) {

    return String(value ?? "")
        .replace(/\s+/g, " ")
        .trim();

}


// =====================================
// Translate Text
// =====================================

function translateText(value, language) {

    const original = String(value ?? "");

    if (language !== "ar") {
        return original;
    }

    const key = normalize(original);

    return translations[key] || original;

}


// =====================================
// Translate Text Node
// =====================================

function translateTextNode(node, language) {

    // Save the original text only once.
    if (!originalTextNodes.has(node)) {
        originalTextNodes.set(node, node.nodeValue);
    }

    const original = originalTextNodes.get(node);
    const key = normalize(original);

    if (!key) {
        return;
    }

    let translated = original;

    if (language === "ar" && translations[key]) {

        // Preserve whitespace before and after the text.
        const leadingSpaces = original.match(/^\s*/)?.[0] || "";
        const trailingSpaces = original.match(/\s*$/)?.[0] || "";

        translated =
            leadingSpaces +
            translations[key] +
            trailingSpaces;

    }

    if (node.nodeValue !== translated) {
        node.nodeValue = translated;
    }

}


// =====================================
// Translate Element Attributes
// =====================================

function translateAttributes(element, language) {

    const attributes = [
        "placeholder",
        "title",
        "aria-label",
        "alt"
    ];

    if (!originalAttributes.has(element)) {
        originalAttributes.set(element, {});
    }

    const savedAttributes = originalAttributes.get(element);

    attributes.forEach(attribute => {

        if (!element.hasAttribute(attribute)) {
            return;
        }

        // Save the original attribute only once.
        if (!(attribute in savedAttributes)) {
            savedAttributes[attribute] =
                element.getAttribute(attribute);
        }

        const original = savedAttributes[attribute];

        const translated = translateText(
            original,
            language
        );

        if (element.getAttribute(attribute) !== translated) {
            element.setAttribute(attribute, translated);
        }

    });

}
// =====================================
// Translate HTML Elements
// =====================================

function translateElement(element, language) {

    if (!element) {
        return;
    }

    // Translate Text Node
    if (element.nodeType === Node.TEXT_NODE) {

        translateTextNode(element, language);

        return;
    }

    // Ignore non-element nodes
    if (element.nodeType !== Node.ELEMENT_NODE) {
        return;
    }

    // Do not translate the language toggle button
    if (element.id === "languageToggle") {
        return;
    }

    // Translate Attributes
    translateAttributes(element, language);

    // Translate Child Elements
    Array.from(element.childNodes).forEach(child => {

        translateElement(child, language);

    });

}


// =====================================
// Apply Language
// =====================================

export function applyLanguage(language) {

    const currentLanguage =
        language === "ar" ? "ar" : "en";

    // Change HTML Language
    document.documentElement.lang = currentLanguage;

    // Change Page Direction
    document.documentElement.dir =
        currentLanguage === "ar" ? "rtl" : "ltr";

    // Set Language Data Attribute
    document.documentElement.dataset.language =
        currentLanguage;

    // Translate Page Content
    if (document.body) {

        translateElement(
            document.body,
            currentLanguage
        );

    }

    // Update Language Button
    const button = document.getElementById("languageToggle");

    if (button) {

        button.innerHTML = `
            <i class="fa-solid fa-globe"></i>
            <span>
                ${currentLanguage === "ar" ? "English" : "العربية"}
            </span>
        `;

        button.title =
            currentLanguage === "ar"
                ? "English"
                : "العربية";

        button.setAttribute(
            "aria-label",
            currentLanguage === "ar"
                ? "Switch language to English"
                : "تغيير اللغة إلى العربية"
        );

    }

    // Save Selected Language
    localStorage.setItem(
        "shopora-language",
        currentLanguage
    );

    // Dispatch Language Changed Event
    window.dispatchEvent(
        new CustomEvent("shopora:language-changed", {
            detail: {
                language: currentLanguage
            }
        })
    );

}


// =====================================
// Language Observer
// =====================================

let languageObserver = null;


// =====================================
// Initialize Language
// =====================================

export function initializeLanguage() {

    // Get Saved Language
    const savedLanguage =
        localStorage.getItem("shopora-language") || "en";

    // Get Language Button
    const button = document.getElementById("languageToggle");

    // Add Click Event
    if (button && !button.dataset.initialized) {

        button.dataset.initialized = "true";

        button.addEventListener("click", function () {

            const currentLanguage =
                document.documentElement.lang;

            const newLanguage =
                currentLanguage === "ar" ? "en" : "ar";

            applyLanguage(newLanguage);

        });

    }

    // Apply Saved Language
    applyLanguage(savedLanguage);

    // Disconnect Previous Observer
    if (languageObserver) {

        languageObserver.disconnect();

    }

    // Observe New Dynamic Elements
    languageObserver = new MutationObserver(records => {

        const currentLanguage =
            document.documentElement.lang;

        records.forEach(record => {

            record.addedNodes.forEach(node => {

                if (
                    node.nodeType === Node.TEXT_NODE ||
                    node.nodeType === Node.ELEMENT_NODE
                ) {

                    translateElement(
                        node,
                        currentLanguage
                    );

                }

            });

        });

    });

    // Start Observing Page
    languageObserver.observe(document.body, {

        childList: true,

        subtree: true

    });

}


// =====================================
// Get Current Language
// =====================================

export function getCurrentLanguage() {

    return document.documentElement.lang || "en";

}